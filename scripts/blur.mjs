// Tiny blurred placeholders (16px wide WebP as data URIs) for every image in assets/images.
// Run after make-images.mjs / covers.mjs: node scripts/blur.mjs  ->  assets/images/blur.ts
import sharp from "sharp";
import fs from "node:fs";
const dir = "assets/images";
const names = [...new Set(fs.readdirSync(dir).filter((f) => f.endsWith(".webp")).map((f) => f.replace(/\.webp$/, "")))];
const out = {};
for (const n of names) {
  const buf = await sharp(`${dir}/${n}.webp`).resize(16, null, { fit: "inside" }).blur(1).webp({ quality: 40 }).toBuffer();
  out[n] = `data:image/webp;base64,${buf.toString("base64")}`;
}
fs.writeFileSync(`${dir}/blur.ts`, `// Generated by scripts/blur.mjs: 16px blurred placeholders, shown behind each photo until it paints.\nexport const blur: Record<string, string> = ${JSON.stringify(out, null, 2)};\n`);
console.log("blur placeholders:", names.length);
