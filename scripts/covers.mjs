// Renders one discipline-specific cover per program from /poster (own study model, no repeats) into
// assets/images/cover-<slug>.{avif,webp} at 960x600, and rewrites assets/images/covers.ts.
// Usage: node scripts/covers.mjs <baseUrl>   (serve the static export first: node scripts/serve-out.mjs 4173)
import { chromium } from "playwright";
import sharp from "sharp";
import fs from "node:fs";

const base = process.argv[2] ?? "http://localhost:4173/vdc-academy/";

// slug: scene. yaw turns the model, iso isolates a discipline, lod/sim/floor/axis pick the moment.
const scenes = {
  "vdc-professional-bootcamp": "mood=1&lod=400&yaw=0.9&bg=ink",
  "bim-fundamentals-revit": "mood=0&lod=200&yaw=-0.4&bg=paper",
  "revit-architecture": "mood=0&lod=300&iso=architecture&yaw=0.3&bg=paper",
  "revit-structure": "mood=0&lod=300&iso=structure&yaw=-0.9&bg=paper",
  "revit-mep": "mood=0&lod=400&iso=mep&yaw=1.4&bg=paper",
  "low-voltage-bim": "mood=1&lod=400&iso=lowvoltage&yaw=0.5&bg=ink",
  "revit-family-creation": "mood=0&lod=350&iso=mep&yaw=2.2&fit=0.55&bg=paper",
  "navisworks-clash-detection": "mood=1&lod=300&iso=clash&focus=1&yaw=0&bg=ink",
  "4d-5d-simulation": "mood=0&lod=300&sim=0.6&yaw=-1.6&bg=paper",
  "dynamo-for-revit": "mood=0&lod=500&yaw=1.9&bg=paper",
  "bim-management-iso-19650": "mood=1&lod=300&floor=3&yaw=-0.5&bg=ink",
};

const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const lines = [];
for (const [slug, q] of Object.entries(scenes)) {
  const ctx = await browser.newContext({ viewport: { width: 960, height: 600 }, deviceScaleFactor: 1.5 });
  const page = await ctx.newPage();
  await page.goto(`${base}poster/?${q}&gl=force`, { waitUntil: "load" });
  await page.waitForSelector("canvas", { timeout: 60000 });
  await page.waitForTimeout(7000);
  const png = await page.screenshot({ type: "png", timeout: 120000 });
  const img = sharp(png).resize(960, 600);
  await img.clone().avif({ quality: 52, effort: 6 }).toFile(`assets/images/cover-${slug}.avif`);
  await img.clone().webp({ quality: 78 }).toFile(`assets/images/cover-${slug}.webp`);
  console.log(slug, (fs.statSync(`assets/images/cover-${slug}.avif`).size / 1024) | 0, "KB avif");
  const id = slug.replace(/-(\w)/g, (_, ch) => ch.toUpperCase()).replace(/^\d/, "n$&");
  lines.push({ slug, id });
  await ctx.close();
}
await browser.close();

const ts = `// Generated by scripts/covers.mjs: one render of the study model per program (no repeats).
import type { Photo } from "./index";
${lines.map((l) => `import ${l.id}Avif from "./cover-${l.slug}.avif";\nimport ${l.id}Webp from "./cover-${l.slug}.webp";`).join("\n")}

const p = (a: { src: string; width: number; height: number }, w: { src: string }): Photo => ({ avif: a.src, webp: w.src, width: a.width, height: a.height });

export const programCovers: Record<string, Photo> = {
${lines.map((l) => `  "${l.slug}": p(${l.id}Avif, ${l.id}Webp),`).join("\n")}
};
`;
fs.writeFileSync("assets/images/covers.ts", ts);
console.log("wrote assets/images/covers.ts");
