// Renders one discipline-specific cover per program from /poster (own study model, no repeats) into
// assets/images/cover-<slug>.{avif,webp} at 960x600, and rewrites assets/images/covers.ts.
// Usage: node scripts/covers.mjs <baseUrl>   (serve the static export first: node scripts/serve-out.mjs 4173)
import { chromium } from "playwright";
import sharp from "sharp";
import fs from "node:fs";

const base = process.argv[2] ?? "http://localhost:4173/vdc-academy/";

// slug: scene. yaw turns the model, iso isolates a discipline, lod/sim/floor/axis pick the moment.
// Each program has its own procedural discipline scene (components/three/DisciplineScene.tsx)
const slugs = ["vdc-professional-bootcamp","bim-fundamentals-revit","revit-architecture","revit-structure","revit-mep","low-voltage-bim","revit-family-creation","navisworks-clash-detection","4d-5d-simulation","dynamo-for-revit","bim-management-iso-19650"];
const scenes = Object.fromEntries(slugs.map((s) => [s, `scene=${s}&bg=paper`]));

// alt text comes from the scene definitions
const altSrc = fs.readFileSync("components/three/DisciplineScene.tsx", "utf8");
const alts = Object.fromEntries(slugs.map((s) => [s, (altSrc.match(new RegExp(`"${s}": \{[^}]*alt: "([^"]+)"`)) || [])[1] ?? ""]));
const browser = await chromium.launch({ args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const lines = [];
for (const [slug, q] of Object.entries(scenes)) {
  const ctx = await browser.newContext({ viewport: { width: 1600, height: 1000 }, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  await page.goto(`${base}poster/?${q}&gl=force`, { waitUntil: "load" });
  await page.waitForSelector("canvas", { timeout: 60000 });
  await page.waitForTimeout(9000);
  const png = await page.screenshot({ type: "png", timeout: 120000 });
  const img = sharp(png);
  await img.clone().resize(1600, 1000).avif({ quality: 50, effort: 6 }).toFile(`assets/images/cover-${slug}.avif`);
  await img.clone().resize(1600, 1000).webp({ quality: 76 }).toFile(`assets/images/cover-${slug}.webp`);
  await img.clone().resize(800, 500).avif({ quality: 52, effort: 6 }).toFile(`assets/images/cover-${slug}-sm.avif`);
  await img.clone().resize(800, 500).webp({ quality: 78 }).toFile(`assets/images/cover-${slug}-sm.webp`);
  console.log(slug, (fs.statSync(`assets/images/cover-${slug}.avif`).size / 1024) | 0, "KB avif");
  const id = slug.replace(/-(\w)/g, (_, ch) => ch.toUpperCase()).replace(/^\d/, "n$&");
  lines.push({ slug, id });
  await ctx.close();
}
await browser.close();

// The index: one entry per program with both sizes and the alt text from the scene definitions.
const out = [];
out.push("// Generated by scripts/covers.mjs: one discipline scene per program (no repeats), 1600x1000 and 800x500.");
out.push('import type { Photo } from "./index";');
out.push('import { blur } from "./blur";');
for (const l of lines) {
  out.push(`import ${l.id}Avif from "./cover-${l.slug}.avif";`);
  out.push(`import ${l.id}Webp from "./cover-${l.slug}.webp";`);
  out.push(`import ${l.id}AvifSm from "./cover-${l.slug}-sm.avif";`);
  out.push(`import ${l.id}WebpSm from "./cover-${l.slug}-sm.webp";`);
}
out.push("");
out.push("const p = (a: { src: string; width: number; height: number }, w: { src: string }, as: { src: string }, ws: { src: string }, name: string): Photo => ({ avif: a.src, webp: w.src, width: a.width, height: a.height, avifSm: as.src, webpSm: ws.src, blur: blur[name] });");
out.push("");
out.push("export const coverAlt: Record<string, string> = " + JSON.stringify(Object.fromEntries(slugs.map((s) => [s, alts[s]])), null, 2) + ";");
out.push("");
out.push("export const programCovers: Record<string, Photo> = {");
for (const l of lines) out.push(`  "${l.slug}": p(${l.id}Avif, ${l.id}Webp, ${l.id}AvifSm, ${l.id}WebpSm, "cover-${l.slug}"),`);
out.push("};");
fs.writeFileSync("assets/images/covers.ts", out.join("\n") + "\n");
console.log("wrote assets/images/covers.ts");
